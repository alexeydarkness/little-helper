CREATE TABLE lessons (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tutor_id    BIGINT NOT NULL REFERENCES users(id),
    student_id  BIGINT NOT NULL REFERENCES users(id),
    subject     VARCHAR(100) NOT NULL,
    lesson_date DATE NOT NULL,
    start_time  TIME NOT NULL,
    end_time    TIME NOT NULL,
    homework    VARCHAR(2000),
    comment     VARCHAR(2000),
    paid        BOOLEAN NOT NULL DEFAULT FALSE,
    CHECK (end_time > start_time),
    CHECK (tutor_id <> student_id)
);

CREATE INDEX lessons_tutor_date ON lessons(tutor_id, lesson_date);
CREATE INDEX lessons_student_date ON lessons(student_id, lesson_date);
